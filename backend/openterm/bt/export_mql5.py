"""BT EXPORT as a MetaTrader 5 Expert Advisor (MQL5) for a RULE strategy: the same rule coverage as the Pine export
(`export.pine_script`). Python strategies are refused by the caller (code cannot be translated faithfully, spec decision J).
The signal is read on the last closed bar and traded at the new bar's open, like OpenTerm. The text is a translation,
never compiled or run here."""

from __future__ import annotations

from .job import HEADLINE
from .rules import BoolOp, Cmp, Term, parse

_TF = {"1D": "PERIOD_D1", "1W": "PERIOD_W1"}
_CMP = {">": "GT", "<": "LT", ">=": "GE", "<=": "LE"}
_PRICE = {"CLOSE": "iClose", "OPEN": "iOpen", "HIGH": "iHigh", "LOW": "iLow"}
_Cross = tuple[str, str, str, str]


def _term(t: Term, shift: str, used: set[tuple[str, int]]) -> str:
    n = int(t.n)
    if t.kind == "NUM":
        return f"{t.n:g}"
    if t.kind == "FIELD":
        return f"(double)iVolume(_Symbol, TF, {shift})" if t.name == "VOLUME" else f"{_PRICE[t.name]}(_Symbol, TF, {shift})"
    if t.kind in ("SMA", "EMA", "RSI"):
        used.add((t.kind.lower(), n))
        return f"BufValue(h_{t.kind.lower()}{n}, {shift})"
    return {"HIGH": f"HighestHigh({n}, {shift})", "LOW": f"LowestLow({n}, {shift})", "RET": f"Ret({n}, {shift})"}[t.kind]


def _expr(node, cross: list[_Cross], used: set[tuple[str, int]]) -> str:
    """MQL5 boolean on the last closed bar; CROSS> / CROSS< become global flags updated once per bar (as in the Pine export)."""
    if isinstance(node, BoolOp):
        return "(" + f" {'&&' if node.op == 'AND' else '||'} ".join(_expr(x, cross, used) for x in node.items) + ")"
    assert isinstance(node, Cmp)
    if node.op in ("CROSS>", "CROSS<"):
        args = ", ".join(_term(t, s, used) for t, s in ((node.left, "1"), (node.left, "2"), (node.right, "1"), (node.right, "2")))
        up, down = ("CrossUp", "CrossDown") if node.op == "CROSS>" else ("CrossDown", "CrossUp")
        cross.append((f"cross{len(cross)}", up, args, down))
        return cross[-1][0]
    return f"{_CMP[node.op]}({_term(node.left, '1', used)}, {_term(node.right, '1', used)})"


_HELPERS = """\
bool GT(double a, double b) { return a != EMPTY_VALUE && b != EMPTY_VALUE && a > b; }
bool LT(double a, double b) { return a != EMPTY_VALUE && b != EMPTY_VALUE && a < b; }
bool GE(double a, double b) { return a != EMPTY_VALUE && b != EMPTY_VALUE && a >= b; }
bool LE(double a, double b) { return a != EMPTY_VALUE && b != EMPTY_VALUE && a <= b; }
bool Known(double a1, double a2, double b1, double b2) { return a1 != EMPTY_VALUE && a2 != EMPTY_VALUE && b1 != EMPTY_VALUE && b2 != EMPTY_VALUE; }
bool CrossUp(double a1, double a2, double b1, double b2)   { return Known(a1, a2, b1, b2) && a1 > b1 && a2 <= b2; }
bool CrossDown(double a1, double a2, double b1, double b2) { return Known(a1, a2, b1, b2) && a1 < b1 && a2 >= b2; }

double BufValue(int handle, int shift)
{
   double buf[1];
   if(CopyBuffer(handle, 0, shift, 1, buf) != 1) return EMPTY_VALUE;
   return buf[0];
}
double HighestHigh(int n, int shift)
{
   if(Bars(_Symbol, TF) < shift + n) return EMPTY_VALUE;
   int i = iHighest(_Symbol, TF, MODE_HIGH, n, shift);
   return i < 0 ? EMPTY_VALUE : iHigh(_Symbol, TF, i);
}
double LowestLow(int n, int shift)
{
   if(Bars(_Symbol, TF) < shift + n) return EMPTY_VALUE;
   int i = iLowest(_Symbol, TF, MODE_LOW, n, shift);
   return i < 0 ? EMPTY_VALUE : iLow(_Symbol, TF, i);
}
double Ret(int n, int shift)
{
   double now = iClose(_Symbol, TF, shift), then = iClose(_Symbol, TF, shift + n);
   return (now <= 0 || then <= 0) ? EMPTY_VALUE : now / then - 1.0;
}

// +1 long, -1 short, 0 flat: this EA's magic number on this symbol
int CurrentSide()
{
   for(int i = PositionsTotal() - 1; i >= 0; i--)
   {
      if(PositionGetSymbol(i) != _Symbol || PositionGetInteger(POSITION_MAGIC) != InpMagic) continue;
      return PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_BUY ? 1 : -1;
   }
   return 0;
}
"""


def mql5_expert(rule: str, *, short: bool, cash: float, fees_bps: float, symbols: list[str], interval: str) -> str:
    cross: list[_Cross] = []
    used: set[tuple[str, int]] = set()
    cond = _expr(parse(rule), cross, used)
    handles = sorted(used, key=lambda x: (x[1], x[0]))
    h = lambda k, n: f"h_{k}{n}"
    out = [
        f"// {HEADLINE}",
        "// GENERATED by OpenTerm from the rule below. UNTESTED ON A LIVE ACCOUNT: compile it in MetaEditor and run it in the",
        "// Strategy Tester on a demo account first. Expect different results from OpenTerm: EMA / RSI seeding, lot sizing,",
        "// spreads, swaps and OpenTerm's per-market cost stack and slippage are not reproduced; MT5 volume is tick volume.",
        f"// RULE: {' '.join(rule.split())}",
        f"// RUN: {', '.join(symbols)} {interval}; initial cash {cash:g}; fees {fees_bps:g} bps (set costs in the tester instead)",
        "// An EA trades its chart symbol: attach it to each symbol of the run separately.",
        "#property strict",
        '#property description "OpenTerm BT rule strategy - HISTORICAL SIMULATION, NOT A FORECAST"',
        "#include <Trade/Trade.mqh>",
        "",
        "input double          InpLots    = 1.0;   // fixed lot size (OpenTerm sizes by equity: adjust to your account)",
        f"input ENUM_TIMEFRAMES TF         = {_TF.get(interval, 'PERIOD_D1')};",
        f"input bool            AllowShort = {'true' if short else 'false'};",
        "input long            InpMagic   = 20250101;",
        "",
        "CTrade   trade;",
        "datetime lastBar = 0;",
        *[f"int      {h(k, n)} = INVALID_HANDLE;" for k, n in handles],
        *[f"bool     {c[0]} = false;" for c in cross],
        "",
        _HELPERS,
        "int OnInit()",
        "{",
        "   trade.SetExpertMagicNumber(InpMagic);",
    ]
    for k, n in handles:
        out.append(f"   {h(k, n)} = iRSI(_Symbol, TF, {n}, PRICE_CLOSE);" if k == "rsi"
                   else f"   {h(k, n)} = iMA(_Symbol, TF, {n}, 0, MODE_{k.upper()}, PRICE_CLOSE);")
        out.append(f"   if({h(k, n)} == INVALID_HANDLE) return INIT_FAILED;")
    out += [
        "   return INIT_SUCCEEDED;",
        "}",
        "",
        "void OnDeinit(const int reason)",
        "{",
        *[f"   if({h(k, n)} != INVALID_HANDLE) IndicatorRelease({h(k, n)});" for k, n in handles],
        "}",
        "",
        "void OnTick()",
        "{",
        "   datetime bar = iTime(_Symbol, TF, 0);",
        "   if(bar == 0 || bar == lastBar) return;   // once per new bar: decide on the last closed bar, trade at this bar's open",
        "   lastBar = bar;",
        *[f"   if({up}({args})) {name} = true; else if({down}({args})) {name} = false;" for name, up, args, down in cross],
        f"   bool signal = {cond};",
        "   int side = CurrentSide();",
        "   if(signal)",
        "   {",
        "      if(side < 0) trade.PositionClose(_Symbol);",
        "      if(side <= 0) trade.Buy(InpLots, _Symbol);",
        "   }",
        "   else",
        "   {",
        "      if(side > 0) trade.PositionClose(_Symbol);",
        "      if(AllowShort && side >= 0) trade.Sell(InpLots, _Symbol);",
        "   }",
        "}",
    ]
    return "\n".join(out) + "\n"
